/* 단지 시설(assets/fac-view.js): node tools/fac-test.js
   - 숫자는 공개 자료(data/fac/sNN.json) 그대로, 자료가 없는 단지는 칸을 아예 안 보여 줌(지어내지 않음)
   - 세대당 주차대수는 엔진이 계산한 값을 그대로(세대수를 믿을 수 없으면 총 대수만)
   - '관리사무소가 등록한 정보예요. 실제와 다를 수 있어요' + 출처·조회일, 원문 보기
   - 쉬운 말, '시험·검증·채점' 안 씀, 다른 업체 이름 없음 */
const L = require('../assets/fac-view.js');
let ok = 0, bad = 0;
const eq = (a, b, m) => { if (JSON.stringify(a) === JSON.stringify(b)) ok++; else { bad++; console.log('FAIL', m, '\n  got:', a, '\n  exp:', b); } };
const has = (a, b, m) => eq(String(a).includes(b), true, m + ' — "' + b + '" in "' + a + '"');
const not = (a, b, m) => eq(String(a).includes(b), false, m + ' — no "' + b + '" in "' + a + '"');

const F = { src: '국토교통부 공동주택관리정보시스템(K-apt)', note: '관리사무소가 등록한 정보예요. 실제와 다를 수 있어요', at: ['2026-11-21', '2026-11-21'],
  u: { 'a|b|1': { f: ['피트니스', '독서실', '어린이집', '경로당', '어린이놀이터'], t: '관리사무소, 피트니스센터, 독서실, 보육시설, 노인정, 어린이놀이터', pk: [12602, 12602, 9510, 1.33], cc: 1450, el: 220, ev: 85, n: '헬리오시티', at: '2026-11-21' },
       'a|b|2': { pk: [400, 300, null, null], n: 'x', at: '2026-11-21' },
       'a|b|3': { f: ['경로당'], pk: [517, 500, 450, 1.15], n: '가', at: '2026-11-21' },
       'a|b|3|나단지': { f: ['수영장'], n: '나', at: '2026-11-21' },
       'a|b|4': { n: '빈 단지', at: '2026-11-21' } } };

/* 1) 자료가 다 있는 큰 단지 */
const o1 = L.unit(F, 'a|b|1', '헬리오시티');
const R1 = L.rows(o1);
eq(R1.map(r => r.k), ['커뮤니티·복리시설', '주차', 'CCTV', '승강기', '전기차 충전기'], '항목 순서');
eq(R1[0].chips, ['피트니스', '독서실', '어린이집', '경로당', '어린이놀이터'], '정리한 시설 이름 그대로');
eq(R1[1].v, '세대당 1.33대 · 총 12,602대(모두 지하)', '주차: 세대당·총 대수');
has(R1[1].sub, '세대 수(9,510세대)로 나눈 값', '세대당 뜻 풀이');
eq([R1[2].v, R1[3].v, R1[4].v], ['1,450대', '220대', '85대'], 'CCTV·승강기·충전기 그대로');
const H1 = L.html(o1, F);
has(H1, '관리사무소가 등록한 정보예요. 실제와 다를 수 있어요', '안내 문장');
has(H1, '출처: 국토교통부 공동주택관리정보시스템(K-apt) · 2026.11.21 조회', '출처·조회일');
has(H1, '관리사무소가 적은 원래 글 보기', '원문 보기');
has(H1, '피트니스센터, 독서실, 보육시설', '원문 그대로');
eq(L.compact(o1).replace(/\u00a0/g, ' '), '피트니스 · 독서실 · 어린이집 외 2개 · 세대당 1.33대', '지도 카드 한 줄');
has(L.srcShort(o1), '관리사무소 등록 정보 · K-apt 2026.11.21 조회', '짧은 출처');
eq(L.has(o1, '피트니스'), true, '피트니스 있음');
eq(R1[0].sub, '', '피트니스가 적혀 있으면 안쪽 시설 안내 없음');
const o5 = { f: ['주민공동시설', '경로당'], n: 'k', at: '2026-11-21' };
has(L.rows(o5)[0].sub, '주민공동시설 안에 피트니스·독서실 등이 있는지는 공공 자료에 따로 나오지 않아요', '주민공동시설만 있을 때 안내');

/* 2) 세대수를 믿을 수 없는 단지: 총 대수만 */
const o2 = L.unit(F, 'a|b|2');
eq(L.rows(o2).map(r => r.v), ['총 400대(지하 300대)'], '세대당 계산 안 함');
eq(L.compact(o2), '주차\u00a0총\u00a0400대', '지도 카드: 총 대수만(줄바꿈 없이)');
has(L.rows(o2)[0].sub, '세대당 대수는 계산하지 않았어요', '세대당이 없는 까닭');
not(L.html(o2, F), '원래 글 보기', '원문 없으면 원문 보기 없음');
eq(L.has(o2, '피트니스'), false, '피트니스 없음');

/* 3) 자료가 없는 단지: 아무것도 안 보여 줌 */
eq(L.unit(F, 'a|b|4'), null, '빈 칸뿐인 단지는 없는 단지');
eq(L.unit(F, 'a|b|9'), null, '파일에 없는 단지');
eq([L.html(null, F), L.compact(null), L.rows(null).length], ['', '', 0], '자료 없으면 빈 문자열');
eq(L.unit(null, 'a|b|1'), null, '파일을 못 불러오면 없음');

/* 4) 한 지번에 단지가 여럿: 이름까지 붙은 키 먼저 */
eq(L.unit(F, 'a|b|3', '나단지').f, ['수영장'], '이름 붙은 키');
eq(L.unit(F, 'a|b|3', '다른').f, ['경로당'], '이름 키가 없으면 지번 키');
eq(L.rows(L.unit(F, 'a|b|3')).find(r => r.k === '주차').v, '세대당 1.15대 · 총 517대(지하 500대)', '지하 일부');

/* 5) 말투 */
for (const t of [H1, L.html(o2, F), L.compact(o1)]) { not(t, '시험', '시험'); not(t, '검증', '검증'); not(t, '채점', '채점'); }
console.log(`${ok} 통과, ${bad} 실패`);
process.exit(bad ? 1 : 0);
